/**
 * Regenerates src/formats/q2-classnames.ts from the pinned engine source, so the
 * inspector can say which map entities the unmodified engine would spawn.
 * Run after `ddev engine fetch`: ddev exec node scripts/gen-classnames.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const game = resolve(root, "engine/.upstream/qwasm2/src/game");
const spawn = readFileSync(resolve(game, "g_spawn.c"), "utf8");
const items = readFileSync(resolve(game, "g_items.c"), "utf8");

const table = /static spawn_t spawns\[\] = \{([\s\S]*?)\n\};/.exec(spawn)?.[1];
const itemList = /itemlist\[\] = \{([\s\S]*?)\n\};/.exec(items)?.[1];
if (!table || !itemList) throw new Error("spawn tables not found; upstream layout changed");

const names = new Set<string>();
for (const m of table.matchAll(/\{"([a-z0-9_]+)",\s*SP_/g)) names.add(m[1]!);
for (const m of itemList.matchAll(/\{\s*"((?:item|weapon|ammo|key)_[a-z0-9_]+)"/g)) names.add(m[1]!);

const lock = readFileSync(resolve(root, "engine/upstream.lock"), "utf8");
const commit = /^qwasm2\s+([0-9a-f]{40})/m.exec(lock)![1];

writeFileSync(
  resolve(root, "src/formats/q2-classnames.ts"),
  `// GENERATED by scripts/gen-classnames.ts from Qwasm2 @ ${commit}. Do not edit.
// Entity classnames the unmodified engine's game module can spawn.
export const Q2_CLASSNAMES: ReadonlySet<string> = new Set([
${[...names].sort().map((n) => `  "${n}",`).join("\n")}
]);
`,
);
console.log(`${names.size} classnames written`);
